export function transitAspectText(tp, np, asp) {
  const n = TRANSIT_NATURE[tp] || { name: tp, soft: '', hard: '' };
  const kind = asp.kind;
  const effect = kind === 'conj' ? (n.conj || n.hard) : kind === 'soft' ? n.soft : n.hard;
  return `Сфера: ${NATAL_POINT_THEME[np] || ''}. Характер: ${effect}.`;
}

